#!/usr/bin/env node
// Bundles the deployed contract's interface (its spec) into src/lib/contract-spec.ts, so the app
// builds its contract client instantly instead of downloading the contract's code from RPC on
// every page load (two round trips, several seconds on testnet).
//
//   npm run spec:sync     fetch the deployed contract and rewrite src/lib/contract-spec.ts
//   npm run spec:check    exit 1 if the bundled spec no longer matches the deployed contract
//
// Run spec:sync after every redeploy (or contract upgrade). Contract ID and RPC come from the same
// env vars the app uses, falling back to ../deployments/testnet.json.

import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { contract, rpc } from "@stellar/stellar-sdk";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "src", "lib", "contract-spec.ts");
const deployment = join(here, "..", "..", "deployments", "testnet.json");

function readEnvLocal() {
  const file = join(here, "..", ".env.local");
  if (!existsSync(file)) return {};
  return Object.fromEntries(
    readFileSync(file, "utf8")
      .split(/\r?\n/)
      .map((l) => l.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/))
      .filter(Boolean)
      .map((m) => [m[1], m[2].replace(/^["']|["']$/g, "")]),
  );
}

const env = { ...readEnvLocal(), ...process.env };
const dep = existsSync(deployment) ? JSON.parse(readFileSync(deployment, "utf8").replace(/^﻿/, "")) : {};
const contractId = env.NEXT_PUBLIC_DESPENSA_CONTRACT_ID || dep.contractId;
const rpcUrl = env.NEXT_PUBLIC_STELLAR_RPC_URL || dep.rpcUrl || "https://soroban-testnet.stellar.org";
if (!contractId) {
  console.error("No contract ID: set NEXT_PUBLIC_DESPENSA_CONTRACT_ID or deploy first.");
  process.exit(2);
}

const server = new rpc.Server(rpcUrl);
const wasm = await server.getContractWasmByContractId(contractId);
const wasmHash = createHash("sha256").update(wasm).digest("hex");
const entries = contract.Spec.fromWasm(wasm).entries.map((e) => e.toXDR("base64"));

if (process.argv.includes("--check")) {
  const current = existsSync(out) ? readFileSync(out, "utf8") : "";
  const bundledHash = current.match(/CONTRACT_WASM_HASH = "([0-9a-f]+)"/)?.[1];
  if (bundledHash === wasmHash) {
    console.log(`OK: bundled spec matches ${contractId} (wasm ${wasmHash.slice(0, 12)}…).`);
    process.exit(0);
  }
  console.error(
    `Out of date: ${contractId} runs wasm ${wasmHash.slice(0, 12)}…, bundled spec is from ${bundledHash?.slice(0, 12) ?? "nothing"}. Run: npm run spec:sync`,
  );
  process.exit(1);
}

const body = `// GENERATED by scripts/sync-contract-spec.mjs. Do not edit: run \`npm run spec:sync\` after redeploying.
// The deployed contract's interface, so the app doesn't download the contract code on every load.

/** Contract the spec was read from. */
export const CONTRACT_SPEC_SOURCE = ${JSON.stringify(contractId)};
/** SHA-256 of the deployed wasm. \`npm run spec:check\` compares it with what's on-chain. */
export const CONTRACT_WASM_HASH = ${JSON.stringify(wasmHash)};

/** ScSpecEntry XDR, base64. */
export const CONTRACT_SPEC: string[] = [
${entries.map((e) => `  ${JSON.stringify(e)},`).join("\n")}
];
`;
writeFileSync(out, body);
console.log(`Wrote ${entries.length} spec entries from ${contractId} (wasm ${wasmHash.slice(0, 12)}…) to src/lib/contract-spec.ts`);
